import fs from 'node:fs/promises';
import { Workbook } from '@oai/artifact-tool';
const root = new URL('.', import.meta.url);
const rows = JSON.parse(await fs.readFile(new URL('review_rows.json', root), 'utf8'));
const wb = Workbook.create();
const sheet = wb.worksheets.add('답변 로그 검토');
sheet.getRange(`A1:O${rows.length}`).values = rows;
wb.recalculate();
const actual = sheet.getRange(`A1:O${rows.length}`).values;
if (JSON.stringify(actual) !== JSON.stringify(rows)) throw Error('Cell round-trip mismatch');
const text = '\ufeff' + actual.map(row => row.map(v => '"' + String(v).replaceAll('"','""') + '"').join(',')).join('\r\n') + '\r\n';
await fs.writeFile(new URL('질문별_답변_로그_검토_20261019.csv', root), text, 'utf8');
console.log(JSON.stringify({savedCases: actual.length - 1, columns: actual[0].length}));
