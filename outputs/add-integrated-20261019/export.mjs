import fs from 'node:fs/promises';
import { Workbook } from '@oai/artifact-tool';
const root = new URL('.', import.meta.url);
const rows = JSON.parse(await fs.readFile(new URL('rows.json', root), 'utf8'));
const workbook = Workbook.create();
const sheet = workbook.worksheets.add('테스트 질문');
sheet.getRange(`A1:E${rows.length}`).values = rows;
workbook.recalculate();
const actual = sheet.getRange(`A1:E${rows.length}`).values;
if (JSON.stringify(actual) !== JSON.stringify(rows)) throw Error('Cell mismatch');
const csv = '\ufeff' + actual.map(row => row.map(v => '"' + String(v).replaceAll('"','""') + '"').join(',')).join('\r\n') + '\r\n';
await fs.writeFile(new URL('updated.csv', root), csv, 'utf8');
console.log(JSON.stringify({rows: actual.length-1, columns: actual[0].length}));
