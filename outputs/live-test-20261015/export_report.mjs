import fs from 'node:fs/promises';
import { Workbook } from '@oai/artifact-tool';
const root = new URL('.', import.meta.url);
const rows = JSON.parse(await fs.readFile(new URL('report_rows.json', root), 'utf8'));
const wb = Workbook.create();
const sheet = wb.worksheets.add('테스트 결과');
sheet.getRange(`A1:M${rows.length}`).values = rows;
wb.recalculate();
const values = sheet.getRange(`A1:M${rows.length}`).values;
if (JSON.stringify(rows) !== JSON.stringify(values)) throw Error('Cell mismatch');
const text = '\ufeff' + values.map(row => row.map(v => '"' + String(v).replaceAll('"', '""') + '"').join(',')).join('\r\n') + '\r\n';
await fs.writeFile(new URL('테스트결과.csv', root), text, 'utf8');
console.log(JSON.stringify({rows:values.length-1, columns:values[0].length}));
