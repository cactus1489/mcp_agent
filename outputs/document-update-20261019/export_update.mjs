import fs from 'node:fs/promises';
import { Workbook } from '@oai/artifact-tool';
const root = new URL('.', import.meta.url);
const rows = JSON.parse(await fs.readFile(new URL('rows.json', root), 'utf8'));
const wb = Workbook.create();
const sheet = wb.worksheets.add('유형별 테스트');
sheet.getRange(`A1:J${rows.length}`).values = rows;
wb.recalculate();
const values = sheet.getRange(`A1:J${rows.length}`).values;
if (JSON.stringify(rows) !== JSON.stringify(values)) throw Error('Cell round-trip mismatch');
const csv = '\ufeff' + values.map(row => row.map(v => '"' + String(v).replaceAll('"','""') + '"').join(',')).join('\r\n') + '\r\n';
await fs.writeFile(new URL('updated.csv', root), csv, 'utf8');
console.log(JSON.stringify({records: values.length - 1, columns: values[0].length}));
